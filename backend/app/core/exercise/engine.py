# Prescription
# ---------------------------------------------------------------------------


def _rule_fires(rule: Rule, finding: Finding) -> bool:
    if rule.trigger is Trigger.BELOW_NORMAL and finding.direction != "below":
        return False
    if rule.trigger is Trigger.ABOVE_NORMAL and finding.direction != "above":
        return False
    if rule.sign is not None:
        # The rule cares which way a signed metric deviated. `direction` alone is not
        # enough: a value below a band that straddles zero can still be positive.
        actual = "positive" if finding.value >= 0 else "negative"
        if actual != rule.sign:
            return False
    return True


def build_prescription(
    findings: Sequence[Finding], analysis_type: str, *, max_exercises: int = 8
) -> List[Prescription]:
    """
    Rank the exercises this set of findings calls for.

    One exercise reached by several findings is listed once, carrying every reason -
    a patient handed "wall slides" three times with three explanations would reasonably
    conclude the report is broken. Its priority is the sum of the contributions, so an
    exercise that addresses three findings outranks one that addresses a single worse
    one, which is the right call for a home programme where adherence falls off after
    the first handful.

    Capped at `max_exercises` because a twenty-item home programme gets done by nobody.
    The cap is applied after ranking, so what survives is the highest-value work.
    """
    severity_points = {"marked": 30, "moderate": 20, "mild": 10, "borderline": 0}

    merged: Dict[str, Prescription] = {}

    for finding in findings:
        # A borderline finding is inside measurement noise. It is shown to the
        # clinician, and it prescribes nothing by itself.
        if not finding.actionable:
            continue

        for rule in rules_for_metric(finding.metric_key, analysis_type):
            if not _rule_fires(rule, finding):
                continue

            side = rule.side.value if rule.side is not Side.NONE else finding.side
            points = severity_points.get(finding.severity, 10) * max(rule.weight, 1)
            reason = f"{finding.statement} {rule.rationale}".strip()

            for slug in rule.exercises:
                exercise = EXERCISES_BY_SLUG.get(slug)
                if exercise is None or not slug:
                    # A typo'd slug is caught by library.validate_rules() in the test
                    # suite. Skipping here as well means a bad deploy drops one
                    # exercise rather than failing the whole screening.
                    continue

                existing = merged.get(slug)
                if existing is None:
                    merged[slug] = Prescription(
                        exercise_slug=slug,
                        exercise=exercise,
                        priority=points,
                        severity=finding.severity,
                        reason=reason,
                        trigger_metric_keys=[finding.metric_key],
                        sides=[side] if side != "none" else [],
                    )
                else:
                    existing.priority += points
                    if SEVERITY_ORDER.get(finding.severity, 0) > SEVERITY_ORDER.get(
                        existing.severity, 0
                    ):
                        existing.severity = finding.severity
                    if finding.metric_key not in existing.trigger_metric_keys:
                        existing.trigger_metric_keys.append(finding.metric_key)
                        existing.reason = f"{existing.reason}\n\n{reason}"
                    if side != "none" and side not in existing.sides:
                        existing.sides.append(side)

    ranked = sorted(
        merged.values(),
        key=lambda p: (p.priority, SEVERITY_ORDER.get(p.severity, 0), p.exercise_slug),
        reverse=True,
    )
    return ranked[:max_exercises]


def summarise_findings(findings: Sequence[Finding], analysis_type: str) -> str:
    """
    A paragraph a patient can read at the top of their plan.

    Deliberately says the honest thing when nothing was found, rather than inventing
    reassurance: this screening measured what it could measure, and within that, these
    were the results.
    """
    label = {"POSTURE": "posture", "GAIT": "walking", "ROM": "joint range"}.get(
        analysis_type.upper(), "screening"
    )
    actionable = [f for f in findings if f.actionable]
    borderline = [f for f in findings if not f.actionable]

    if not actionable:
        base = (
            f"Your {label} screening did not find any measurement outside its expected "
            f"range."
        )
        if borderline:
            base += (
                f" {len(borderline)} measurement(s) sat just outside, by less than this "
                f"system can reliably distinguish from measurement error, so they are "
                f"listed for your clinician but not acted on."
            )
        return base

    worst = actionable[0]
    counts = {}
    for f in actionable:
        counts[f.severity] = counts.get(f.severity, 0) + 1
    parts = [
        f"{n} {sev}" for sev, n in sorted(counts.items(), key=lambda kv: -SEVERITY_ORDER.get(kv[0], 0))
    ]
    return (
        f"Your {label} screening found {len(actionable)} measurement(s) outside their "
        f"expected range ({', '.join(parts)}). The most significant was: {worst.statement} "
        f"The exercises below were selected to address what was found, and your "
        f"clinician reviews them before they become your programme."
    )


def plan_title(analysis_type: str) -> str:
    return {
        "POSTURE": "Posture screening exercise programme",
        "GAIT": "Walking screening exercise programme",
        "ROM": "Joint range exercise programme",
    }.get(analysis_type.upper(), "Exercise programme")


def generate(metrics_json: Any, analysis_type: str, *, max_exercises: int = 8) -> Dict[str, Any]:
    """
    One call from a stored analysis to everything needed to write a draft plan.

    Returns a plain dict rather than model objects so the API layer can persist it and
    the report layer can render it without either importing the other.
    """
    findings = extract_findings(metrics_json, analysis_type)
    prescriptions = build_prescription(
        findings, analysis_type, max_exercises=max_exercises
    )
    return {
        "engineVersion": ENGINE_VERSION,
        "analysisType": analysis_type.upper(),
        "title": plan_title(analysis_type),
        "summary": summarise_findings(findings, analysis_type),
        "findings": [f.to_dict() for f in findings],
        "prescriptions": [p.to_dict() for p in prescriptions],
    }
